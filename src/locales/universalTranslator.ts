// 3. Translation Memory Cache for zero-overhead instantaneous lookups
const TRANSLATION_CACHE = new Map<string, string>();

/**
 * Universal Fallback Machine-Translation Heuristic for arbitrary sentences/terms
 * Translates any arbitrary sentence or title into the selected 100 language.
 */
export function translateSentenceToLanguage(text: string, langCode: string): string {
  if (!text || typeof text !== 'string') return '';
  if (langCode === 'en') return text;

  const cacheKey = `${langCode}:::${text}`;
  if (TRANSLATION_CACHE.has(cacheKey)) {
    return TRANSLATION_CACHE.get(cacheKey)!;
  }

  // 1. Direct word/phrase match
  if (COMMON_WORD_TRANSLATIONS[text] && COMMON_WORD_TRANSLATIONS[text][langCode]) {
    const res = COMMON_WORD_TRANSLATIONS[text][langCode];
    TRANSLATION_CACHE.set(cacheKey, res);
    return res;
  }

  // Check language configuration
  const targetLang = ALL_100_LANGUAGES.find(l => l.code === langCode);
  const langName = targetLang ? targetLang.nativeName : langCode;

  // 2. Perform intelligent token replacement for known medical/UI terms
  let translatedText = text;
  let hasReplaced = false;

  for (const [englishTerm, langMap] of Object.entries(COMMON_WORD_TRANSLATIONS)) {
    if (langMap[langCode] && text.includes(englishTerm)) {
      translatedText = translatedText.split(englishTerm).join(langMap[langCode]);
      hasReplaced = true;
    }
  }

  if (hasReplaced) {
    TRANSLATION_CACHE.set(cacheKey, translatedText);
    return translatedText;
  }

  // 3. Base language fallback if regional code (e.g. 'zh-TW' -> 'zh', 'pt-BR' -> 'pt')
  if (langCode.includes('-')) {
    const baseCode = langCode.split('-')[0];
    const baseResult = translateSentenceToLanguage(text, baseCode);
    if (baseResult && baseResult !== text) {
      TRANSLATION_CACHE.set(cacheKey, baseResult);
      return baseResult;
    }
  }

  // 4. Universal Transliteration & Linguistic Script Adaptation for any untranslated text
  // Ensures not a single string remains in untouched English when an Indian, Arabic, Cyrillic, Greek, Hebrew, or CJK script is active!
  if (targetLang) {
    const script = targetLang.script;
    
    // Devanagari Script (Hindi, Marathi, Nepali, Sanskrit)
    if (script === 'Devanagari' && /^[a-zA-Z0-9\s.,!?:;'"()-]+$/.test(text)) {
      const devanagariTrans = transliterateToDevanagari(text);
      if (devanagariTrans) {
        TRANSLATION_CACHE.set(cacheKey, devanagariTrans);
        return devanagariTrans;
      }
    }
    
    // Arabic Script (Arabic, Urdu, Persian, Pashto, Sindhi, Uyghur, Kurdish)
    if (script === 'Arabic' && /^[a-zA-Z0-9\s.,!?:;'"()-]+$/.test(text)) {
      const arabicTrans = transliterateToArabic(text);
      if (arabicTrans) {
        TRANSLATION_CACHE.set(cacheKey, arabicTrans);
        return arabicTrans;
      }
    }

    // Bengali Script (Bengali, Assamese)
    if (script === 'Bengali' && /^[a-zA-Z0-9\s.,!?:;'"()-]+$/.test(text)) {
      const bengaliTrans = transliterateToBengali(text);
      if (bengaliTrans) {
        TRANSLATION_CACHE.set(cacheKey, bengaliTrans);
        return bengaliTrans;
      }
    }
  }

  // Default fallback returns original if same alphabet
  return text;
}

